// Builds public/icons.js from Tabler Icons (MIT). Source: $ICON_DIR, ~/Icons/svg/outline,
// or node_modules/@tabler/icons/icons/outline. The output is committed, so this only
// needs to run when the icon list changes.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';

const NAMES = ['home', 'chart-line', 'file-text', 'search', 'bulb', 'target-arrow', 'world-search', 'settings', 'download', 'refresh',
  'external-link', 'copy', 'trash', 'trending-up', 'trending-down', 'minus', 'moon', 'sun', 'key', 'plug-connected', 'alert-triangle',
  'info-circle', 'arrow-left', 'device-desktop', 'world', 'list-check', 'sitemap', 'filter', 'bell', 'folders', 'note', 'calendar-event', 'plus', 'check', 'send'];
const dirs = [process.env.ICON_DIR, join(homedir(), 'Icons/svg/outline'), 'node_modules/@tabler/icons/icons/outline'].filter(Boolean);
const dir = dirs.find((d) => existsSync(join(d, 'home.svg')));
if (!dir) throw new Error('No Tabler icon directory found. Set ICON_DIR.');
const out = {};
for (const n of NAMES) {
  const svg = readFileSync(join(dir, `${n}.svg`), 'utf8')
    .replace(/<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*\/>/, '')
    .replace(/\s*class="[^"]*"/, '')
    .replace(/\s+width="24"\s+height="24"/, '')
    .replace('<svg', '<svg class="icon" aria-hidden="true" focusable="false"')
    .replace(/\s*\n\s*/g, ' ')
    .trim();
  out[n] = svg;
}
writeFileSync('public/icons.js', `// Generated by scripts/build-icons.mjs from Tabler Icons (MIT, https://tabler.io/icons).\nexport default ${JSON.stringify(out, null, 1)};\n`);
console.log(`Wrote ${NAMES.length} icons from ${dir}`);
