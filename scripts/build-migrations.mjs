// Embeds migrations/*.sql into src/schema.ts so the Worker can apply its own schema
// on first run (one-click deploys never run `wrangler d1 migrations apply`).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const files = readdirSync('migrations').filter((f) => /^\d+_.+\.sql$/.test(f)).sort();
const migrations = files.map((name) => {
  const sql = readFileSync(`migrations/${name}`, 'utf8')
    .split('\n')
    .filter((l) => !l.trim().startsWith('--'))
    .join('\n');
  const statements = sql
    .split(/;\s*(?:\n|$)/)
    .map((s) => s.trim())
    .filter(Boolean);
  return { name, statements };
});
writeFileSync(
  'src/schema.ts',
  `// Generated by scripts/build-migrations.mjs from migrations/*.sql. Do not edit.\nexport const MIGRATIONS: { name: string; statements: string[] }[] = ${JSON.stringify(migrations, null, 2)};\n`,
);
console.log(`Embedded ${migrations.length} migrations`);
